package report

import (
	"encoding/json"
	"sort"
	"strings"

	"pentagi/pkg/database"
)

// defaultReportLabels is the English wording of every fixed label the composed
// sections render. The planner returns a translation of this set for the
// report's language; a key it omits (or a report with no labels at all) falls
// back to the English text here (plan § 6.11). Values may carry [[name]]
// placeholders, which the composer fills with the report data. Brackets, not
// braces: the planner prompt is a Go text/template and would parse {{name}}.
var defaultReportLabels = map[string]string{
	// Cover page.
	"cover.engagement": "Engagement: [[template]] (flow [[id]])",
	"cover.generated":  "Generated [[date]].",

	// Engagement metrics table.
	"metrics.metric":         "Metric",
	"metrics.value":          "Value",
	"metrics.took":           "Took",
	"metrics.agent_time":     "Agent time",
	"metrics.tokens":         "Tokens",
	"metrics.sections":       "Sections",
	"metrics.tokens_value":   "[[in]] in · [[out]] out",
	"metrics.sections_value": "[[done]] of [[total]] (estimate [[estimate]])",

	// Risk rankings table.
	"rankings.rank":  "Rank",
	"rankings.where": "Where to read",
	"rankings.item":  "Item",
	"rankings.empty": "*Composed from the document when the report is exported: no ranking material in this document.*",

	// Document version.
	"version.document_version": "- Document version: 1",
	"version.template":         "- Template: [[template]]",
	"version.generated":        "- Generated: [[date]]",

	// Closing.
	"closing.end": "*End of report. The engagement record this document was written from stays with the flow; this run took [[took]] in agent time [[agent_time]] ([[tokens_in]] in · [[tokens_out]] out).*",

	// Page header and footer.
	"header_footer.line": "Header: \"[[title]]\" | Footer: \"Generated by PentAGI · [[date]]\"",
}

// resolveLabels merges the report's stored label translations over the English
// defaults, so a missing or malformed column yields today's wording.
func resolveLabels(report database.Report) map[string]string {
	labels := make(map[string]string, len(defaultReportLabels))
	for key, value := range defaultReportLabels {
		labels[key] = value
	}
	if !report.Labels.Valid || len(report.Labels.RawMessage) == 0 {
		return labels
	}

	translated := map[string]string{}
	if err := json.Unmarshal(report.Labels.RawMessage, &translated); err != nil {
		return labels
	}
	for key, value := range translated {
		if strings.TrimSpace(value) != "" {
			labels[key] = value
		}
	}
	return labels
}

// renderLabel fills a label's [[name]] placeholders with their values. Unknown
// placeholders are left as written, never swallowed. An absent key renders the
// empty string rather than panicking.
func renderLabel(labels map[string]string, key string, vars map[string]string) string {
	text := labels[key]
	for name, value := range vars {
		text = strings.ReplaceAll(text, "[["+name+"]]", value)
	}
	return text
}

// decodeLabels reads the planner's label map leniently: the field is optional
// and a model that stringifies it, or emits a malformed object, must not sink
// the whole plan (the report then keeps the English wording).
func decodeLabels(raw json.RawMessage) map[string]string {
	if len(raw) == 0 {
		return nil
	}
	if raw[0] == '"' {
		var asText string
		if err := json.Unmarshal(raw, &asText); err != nil {
			return nil
		}
		raw = []byte(asText)
	}
	if len(raw) == 0 || raw[0] != '{' {
		return nil
	}
	labels := map[string]string{}
	if err := json.Unmarshal(raw, &labels); err != nil {
		return nil
	}
	return labels
}

// labelKeySet is the label set the planner is asked to translate; exported so
// the prompt and a test stay in sync.
func labelKeySet() []string {
	keys := make([]string, 0, len(defaultReportLabels))
	for key := range defaultReportLabels {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
