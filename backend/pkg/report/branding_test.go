func pngBytes(size int) []byte {
	out := make([]byte, 0, size)
	out = append(out, 0x89, 'P', 'N', 'G', 0x0D, 0x0A, 0x1A, 0x0A)
	for len(out) < size {
		out = append(out, 0x00)
	}
	return out
}

func jpegBytes(size int) []byte {
	out := []byte{0xFF, 0xD8, 0xFF, 0xE0}
	for len(out) < size {
		out = append(out, 0x00)
	}
	return out
}

func TestDecodeBrandingLogo(t *testing.T) {
	t.Run("accepts a data URL and a raw base64 payload", func(t *testing.T) {
		raw := base64.StdEncoding.EncodeToString(pngBytes(64))

		fromURL, err := DecodeBrandingLogo("data:image/png;base64,"+raw, "brand.png")
		require.NoError(t, err)
		assert.Equal(t, "image/png", fromURL.MediaType)
		assert.Equal(t, "brand.png", fromURL.Name)
		assert.Len(t, fromURL.Bytes, 64)

		fromRaw, err := DecodeBrandingLogo(raw, "")
		require.NoError(t, err)
		assert.Equal(t, "logo.png", fromRaw.Name, "a missing name falls back to the detected type")
	})

	t.Run("sniffs the type rather than trusting the label", func(t *testing.T) {
		raw := base64.StdEncoding.EncodeToString(jpegBytes(32))

		logo, err := DecodeBrandingLogo("data:image/png;base64,"+raw, "photo.jpg")
		require.NoError(t, err)
		assert.Equal(t, "image/jpeg", logo.MediaType)
	})

	t.Run("rejects what the renderers cannot draw", func(t *testing.T) {
		_, err := DecodeBrandingLogo("data:image/svg+xml;base64,"+base64.StdEncoding.EncodeToString([]byte("<svg/>")), "x")
		assert.ErrorContains(t, err, "unsupported logo type")

		_, err = DecodeBrandingLogo("!!!not base64!!!", "x")
		assert.Error(t, err)
	})

	t.Run("bounds the size", func(t *testing.T) {
		raw := base64.StdEncoding.EncodeToString(pngBytes(BrandingMaxLogoBytes + 1))

		_, err := DecodeBrandingLogo(raw, "big.png")
		assert.ErrorContains(t, err, "the limit is")
	})

	t.Run("sanitizes the stored name", func(t *testing.T) {
		raw := base64.StdEncoding.EncodeToString(pngBytes(16))

		logo, err := DecodeBrandingLogo(raw, "../../etc/logo.png")
		require.NoError(t, err)
		assert.Equal(t, "..-..-etc-logo.png", logo.Name)
	})
}

